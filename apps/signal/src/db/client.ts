import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { drizzle as drizzlePg } from "drizzle-orm/node-postgres";
import { migrate as migratePg } from "drizzle-orm/node-postgres/migrator";
import type { PgDatabase, PgQueryResultHKT } from "drizzle-orm/pg-core";
import pg from "pg";
import * as schema from "./schema.js";

/** A Drizzle database, whichever driver is behind it. */
export type Db = PgDatabase<PgQueryResultHKT, typeof schema>;

export interface Database {
  db: Db;
  /** Human-readable description for logs. */
  kind: string;
  close(): Promise<void>;
}

/** SQL migrations generated by drizzle-kit (apps/signal/drizzle). */
const MIGRATIONS = resolve(import.meta.dirname, "../../drizzle");

/**
 * Opens the database and brings its tables up to date.
 *
 * - `postgres://...`  real Postgres (docker compose up -d, or a hosted one)
 * - `pglite:<folder>` PGlite: actual Postgres compiled to WebAssembly, running
 *                     inside this Node process. No install, good for quick
 *                     local runs and tests. `pglite:memory` keeps nothing.
 */
export async function openDatabase(url: string): Promise<Database> {
  if (url.startsWith("pglite:")) {
    // Loaded only when used, so production (real Postgres) doesn't need it.
    const { PGlite } = await import("@electric-sql/pglite");
    const { drizzle } = await import("drizzle-orm/pglite");
    const { migrate } = await import("drizzle-orm/pglite/migrator");
    const location = url.slice("pglite:".length);
    if (location !== "memory") mkdirSync(location, { recursive: true });
    const client = location === "memory" ? new PGlite() : new PGlite(location);
    const db = drizzle(client, { schema });
    await migrate(db, { migrationsFolder: MIGRATIONS });
    return {
      db: db as unknown as Db,
      kind: location === "memory" ? "PGlite (in memory)" : `PGlite (${location})`,
      close: () => client.close(),
    };
  }

  const pool = new pg.Pool({ connectionString: url, max: 10 });
  const db = drizzlePg(pool, { schema });
  await migratePg(db, { migrationsFolder: MIGRATIONS });
  const host = new URL(url).host;
  return { db: db as unknown as Db, kind: `Postgres (${host})`, close: () => pool.end() };
}
